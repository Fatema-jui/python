import math 
a = 4.5
print(math.ceil(a)) #rounds up to the nearest integer
print(math.floor(a)) #rounds down to the nearest integer
print(math.trunc(a)) #truncates the decimal part
print(math.copysign(a, -6)) #returns magnitude of a with sign of -1
print(math.fabs(a)) #returns absolute value of a
print(math.factorial(4)) #returns factorial of 4